// Client copies of the rules in api_server/src/schema/types.rs. They save a
// round trip; the server's check is the one that counts.

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/

export const PROMPT_MIN = 10
export const PROMPT_MAX = 2000

// The server counts characters, not UTF-16 units.
export function charCount(text: string): number {
  return [...text].length
}

export function normaliseEmail(email: string): string {
  return email.trim().toLowerCase()
}

export function emailError(email: string): string | null {
  return EMAIL.test(email) ? null : 'Please enter a valid email address'
}

export function usernameError(username: string): string | null {
  const length = charCount(username)
  return length >= 3 && length <= 30 ? null : 'Username must be between 3 and 30 characters'
}

export function passwordError(password: string): string | null {
  const length = charCount(password)
  return length >= 8 && length <= 72 ? null : 'Password must be between 8 and 72 characters'
}

export function promptError(prompt: string): string | null {
  const length = charCount(prompt)
  return length >= PROMPT_MIN && length <= PROMPT_MAX
    ? null
    : `Prompt must be between ${PROMPT_MIN} and ${PROMPT_MAX} characters`
}

// 20 random bytes as hex, as generated by forgot-password.
export function isResetToken(token: string | undefined): token is string {
  return token !== undefined && /^[0-9a-f]{40}$/.test(token)
}

export function passwordStrength(password: string): { score: 0 | 1 | 2 | 3 | 4; label: string } {
  let score = 0
  if (password.length >= 8) score++
  if (password.length >= 12) score++
  if (/[A-Z]/.test(password) && /[a-z]/.test(password)) score++
  if (/\d/.test(password) && /[^A-Za-z0-9]/.test(password)) score++
  const s = Math.min(4, score) as 0 | 1 | 2 | 3 | 4
  return { score: s, label: ['Too short', 'Weak', 'Fair', 'Strong', 'Excellent'][s] }
}
