// Records kept in this browser (IndexedDB). None of these exist on the server.
import type { Library } from '@/lib/api/types'
import type { Timeline } from '@/features/editor/model/timeline'
import { table, uid } from './db'

/** A job this browser created. The server has no "list my jobs" endpoint. */
export interface JobRecord {
  id: string
  owner: string
  prompt: string
  library: Library
  createdAt: number
  /** Options chosen in Prompt Studio; folded into the prompt text the server receives. */
  options: { aspect: string; duration: number; style: string; brandKitId: string | null }
}

export type MediaKind = 'video' | 'audio' | 'image'

export interface MediaAsset {
  id: string
  owner: string
  name: string
  kind: MediaKind
  mime: string
  size: number
  /** OPFS path of the original file. */
  path: string
  duration: number
  width: number
  height: number
  hasAudio: boolean
  videoCodec: string | null
  audioCodec: string | null
  /** Which demuxer read it: the Rust offcut-mp4 crate or mediabunny. */
  demuxer: 'offcut-mp4' | 'mediabunny' | 'image'
  sha256: string
  createdAt: number
  /** Animato job this asset came from, if any. */
  jobId: string | null
  /** JPEG data URLs of evenly spaced frames, generated by the media worker. */
  thumbnails: string[]
  /** Peak amplitudes (0..1), 100 per second. */
  waveform: number[]
}

export interface Project {
  id: string
  owner: string
  name: string
  tags: string[]
  createdAt: number
  updatedAt: number
  /** JPEG data URL of a real frame. */
  thumbnail: string | null
  timeline: Timeline
}

export interface BrandKit {
  id: string
  owner: string
  name: string
  colors: string[]
  headingFont: string
  bodyFont: string
  logoAssetId: string | null
  logoDataUrl: string | null
  tone: string
  appendToPrompts: boolean
  updatedAt: number
}

export interface ExportRecord {
  id: string
  owner: string
  projectId: string
  projectName: string
  fileName: string
  format: 'mp4' | 'webm'
  videoCodec: string
  width: number
  height: number
  duration: number
  size: number
  createdAt: number
  /** OPFS path of the exported file, kept for re-download. */
  path: string
}

export const jobsTable = table<JobRecord>('jobs')
export const mediaTable = table<MediaAsset>('media')
export const projectsTable = table<Project>('projects')
export const brandTable = table<BrandKit>('brand')
export const exportsTable = table<ExportRecord>('exports')

export async function mine<T extends { owner: string }>(
  t: { all: () => Promise<T[]> },
  owner: string,
): Promise<T[]> {
  return (await t.all()).filter((r) => r.owner === owner)
}

export { uid }
